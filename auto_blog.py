
import json
import html
import re
from pathlib import Path
from datetime import datetime, timedelta, timezone
from urllib.request import Request, urlopen
from urllib.parse import urlsplit, urlunsplit

NEWS_URL = "https://news.btcbrave.store/news.json"
POSTS_FILE = Path("posts.json")
MAX_DAILY = 4

CATEGORIES = [
    "crypto",
    "finance",
    "technology",
    "ai",
    "world",
]


def clean_text(value):
    value = html.unescape(str(value or ""))
    value = re.sub(r"<[^>]+>", " ", value)
    return re.sub(r"\s+", " ", value).strip()


def parse_date(value):
    try:
        dt = datetime.fromisoformat(
            str(value).replace("Z", "+00:00")
        )
        if dt.tzinfo is None:
            dt = dt.replace(tzinfo=timezone.utc)
        return dt.astimezone(timezone.utc)
    except (ValueError, TypeError):
        return None


def clean_url(value):
    try:
        parsed = urlsplit(str(value).strip())
        if parsed.scheme not in ("https", "http"):
            return ""
        if not parsed.netloc:
            return ""
        return urlunsplit((
            parsed.scheme.lower(),
            parsed.netloc.lower(),
            parsed.path.rstrip("/"),
            "",
            "",
        ))
    except ValueError:
        return ""


def fetch_news():
    request = Request(
        NEWS_URL,
        headers={
            "User-Agent": "BTCBRAVE-Blog/1.0",
            "Accept": "application/json",
        },
    )

    with urlopen(request, timeout=30) as response:
        news = json.load(response)

    if not isinstance(news, list):
        raise ValueError("Invalid news.json format")

    return news


def load_posts():
    if not POSTS_FILE.exists():
        raise FileNotFoundError("posts.json not found")

    posts = json.loads(
        POSTS_FILE.read_text(encoding="utf-8-sig")
    )

    if not isinstance(posts, list):
        raise ValueError("Invalid posts.json format")

    return posts


def create_post(article, now):
    title = clean_text(article["title"])[:180]
    description = clean_text(article["description"])

    words = description.split()
    summary = " ".join(words[:20])

    if len(words) > 20:
        summary += "..."

    original_url = article["link"]
    domain = urlsplit(original_url).hostname or "Publisher"
    publisher = domain.removeprefix("www.")

    safe_summary = html.escape(summary)
    safe_publisher = html.escape(publisher)
    safe_url = html.escape(original_url, quote=True)

    full_text = (
        "<p><strong>BTCBRAVE News Brief</strong></p>"
        f"<p>Source: {safe_publisher}</p>"
        f"<blockquote>{safe_summary}</blockquote>"
        "<p>This news brief is based on the "
        "publisher's RSS summary. "
        "For the full story and further details, "
        "visit the original source.</p>"
        f'<p><a href="{safe_url}" target="_blank" '
        'rel="noopener noreferrer">'
        "Read the original article</a></p>"
    )

    thumbnail = str(
        article.get("thumbnail") or ""
    ).strip()

    if not thumbnail.startswith(("http://", "https://")):
        thumbnail = ""

    return {
        "title": title,
        "description": summary,
        "thumbnail": thumbnail,
        "pubDate": now.isoformat(timespec="seconds"),
        "fullText": full_text,
        "category": article["category"],
        "link": "",
        "sourceLink": original_url,
        "source": publisher,
        "autoGenerated": True,
    }


def main():
    print("[START] BTCBRAVE Blog automation", flush=True)

    now = datetime.now(timezone.utc)
    posts = load_posts()

    daily_count = sum(
        1
        for post in posts
        if isinstance(post, dict)
        and post.get("autoGenerated")
        and (parse_date(post.get("pubDate")) or
             datetime.min.replace(
                 tzinfo=timezone.utc
             )).date() == now.date()
    )

    print(
        f"[INFO] Posts published today: "
        f"{daily_count}/{MAX_DAILY}",
        flush=True
    )

    if daily_count >= MAX_DAILY:
        print("[SKIP] Daily limit reached", flush=True)
        return

    used_links = {
        clean_url(post.get("sourceLink") or "")
        for post in posts
        if isinstance(post, dict)
    }

    used_titles = {
        clean_text(post.get("title")).lower()
        for post in posts
        if isinstance(post, dict)
    }

    news = fetch_news()

    print(
        f"[INFO] Available news: {len(news)}",
        flush=True
    )

    candidates = []

    for article in news:
        if not isinstance(article, dict):
            continue

        title = clean_text(article.get("title"))
        description = clean_text(
            article.get("description")
        )
        link = clean_url(article.get("link"))
        published = parse_date(article.get("pubDate"))
        category = str(
            article.get("category") or ""
        ).lower()

        if not title or not link or not published:
            continue
        if category not in CATEGORIES:
            continue
        if len(description) < 60:
            continue
        if link in used_links:
            continue
        if title.lower() in used_titles:
            continue
        if published < now - timedelta(days=3):
            continue
        if published > now + timedelta(minutes=10):
            continue

        candidates.append((published, article))

    if not candidates:
        print(
            "[SKIP] No suitable new articles",
            flush=True
        )
        return

    candidates.sort(
        key=lambda item: item[0],
        reverse=True
    )

    preferred = CATEGORIES[
        (now.toordinal() + daily_count)
        % len(CATEGORIES)
    ]

    selected = next(
        (
            article for _, article in candidates
            if article.get("category") == preferred
        ),
        candidates[0][1]
    )

    post = create_post(selected, now)

    posts.insert(0, post)

    temporary = Path("posts.json.tmp")

    temporary.write_text(
        json.dumps(
            posts,
            ensure_ascii=False,
            indent=2
        ) + "\n",
        encoding="utf-8"
    )

    temporary.replace(POSTS_FILE)

    print("[SUCCESS] Blog post created!", flush=True)
    print("[TITLE]", post["title"], flush=True)
    print("[CATEGORY]", post["category"], flush=True)
    print("[SOURCE]", post["source"], flush=True)
    print("[TOTAL POSTS]", len(posts), flush=True)


if __name__ == "__main__":
    main()

